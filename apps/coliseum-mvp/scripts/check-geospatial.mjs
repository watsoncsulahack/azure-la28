import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {buildEvidenceOverlay} from '../dist/geospatial-overlay.js';
const root=new URL('../dist/',import.meta.url);
const geo=JSON.parse(await readFile(new URL('data/geospatial-evidence.json',root)));
const venue=JSON.parse(await readFile(new URL('data/venue.json',root)));
assert.equal(venue.revision,'0.3.0');
assert.equal(venue.baseGeometryVersion,'0.2.0');
assert.equal(venue.evidenceOverlay.geometryReshapedFromLidar,false);
assert.equal(geo.schemaVersion,'0.3.0');
assert.equal(geo.streetSegments.length,10);
assert.equal(geo.curbRamps.length,20);
assert.equal(new Set(geo.streetSegments.map(x=>x.sourceId)).size,10);
assert.equal(new Set(geo.curbRamps.map(x=>x.sourceId)).size,20);
assert(geo.curbRamps.every(x=>x.createdYear===2017));
assert(geo.curbRamps.every(x=>x.localXZ.every(Number.isFinite)));
assert(geo.streetSegments.every(x=>x.localPaths.every(path=>path.every(point=>point.length===2&&point.every(Number.isFinite)))));
assert.equal(geo.manifest.geoAlignmentStatus,'PROVISIONAL_DIAGNOSTIC_ONLY');
assert.equal(geo.manifest.approvedForPhysicalNavigation,false);
assert.equal(geo.manifest.approvedForGeometryFitting,false);
assert.equal(geo.referenceFootprintBounds.vintage,2008);
assert.equal(geo.referenceFootprintBounds.localCorners.length,4);
const overlay=buildEvidenceOverlay(venue,geo);
assert.equal(overlay.streets,10);
assert.equal(overlay.curbRamps,20);
assert.equal(overlay.navMeshesAdded,0);
assert.equal(overlay.group.children.length,31);
assert(overlay.group.children.every(x=>x.userData?.navigable!==true && x.userData?.passable!==true));
console.log(JSON.stringify({revision:'0.3.0',roadCenterlines:overlay.streets,curbRampRecords:overlay.curbRamps,
 historicalOutlineBounds:1,addedNavigationSurfaces:0,baseGeometryChanged:false,passes:true}));
